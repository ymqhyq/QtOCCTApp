"""Contract-safe RCIF package editing.

Only creative fields are mutable. Derived fields (bounds, volume, checksums,
cache keys, QA) are regenerated by the trusted packer. Every edit produces a
new revision and never mutates the source archive in place.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import tempfile
import zipfile
from collections import OrderedDict
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import cadquery as cq

import rcifc
from glb_writer import write_glb_parts
from generic_rebuild import _execute_generator, _shape, _safe_extract

ALLOWED_IDENTITY = {
    "familyId", "name", "category", "semanticCode", "semanticProfileHint",
    "drawingCode", "designSpeed", "applicableSpan", "placement",
}
SCHEMA_TYPES = {"real", "int", "string", "enum", "bool"}
PRESET_RESERVED = {"cacheKey", "isPrebaked", "label", "drawingCode", "modelNumber", "params"}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _bump_revision(value: str) -> str:
    match = re.match(r"^(\d+)\.(\d+)\.(\d+)$", str(value or "0.0.0"))
    if not match:
        return "0.0.1"
    major, minor, patch = (int(part) for part in match.groups())
    return f"{major}.{minor}.{patch + 1}"


def _clean_identity(identity: dict, updates: dict) -> None:
    for key, value in updates.items():
        if key not in ALLOWED_IDENTITY:
            raise ValueError(f"identity 字段不允许修改: {key}")
        if key == "familyId":
            text = str(value or "").strip()
            if not re.match(r"^[A-Za-z][A-Za-z0-9_]{2,31}$", text):
                raise ValueError("familyId 必须是 3-32 位字母/数字/下划线")
            identity[key] = text
        elif key == "applicableSpan":
            if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
                raise ValueError("applicableSpan 必须是字符串数组")
            identity[key] = [item.strip() for item in value if item.strip()][:20]
        elif key == "placement":
            if not isinstance(value, dict):
                raise ValueError("placement 必须是对象")
            identity[key] = value
        else:
            text = str(value or "").strip()
            if len(text) > 200:
                raise ValueError(f"{key} 过长")
            identity[key] = text


def _validate_schema(schema: list) -> list:
    if not isinstance(schema, list) or not schema:
        raise ValueError("parameters.schema 必须是非空数组")
    names = set()
    result = []
    for item in schema:
        if not isinstance(item, dict):
            raise ValueError("schema 项必须是对象")
        name = str(item.get("name") or "").strip()
        if not re.match(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$", name):
            raise ValueError(f"非法参数名: {name}")
        if name in names:
            raise ValueError(f"参数名重复: {name}")
        names.add(name)
        item_type = str(item.get("type") or "real")
        if item_type not in SCHEMA_TYPES:
            raise ValueError(f"参数 {name} 类型不支持: {item_type}")
        result.append({**item, "name": name})
    return result


def _validate_preset(preset: dict, schema_names: set) -> dict:
    if not isinstance(preset, dict):
        raise ValueError("预设必须是对象")
    model = str(preset.get("modelNumber") or "").strip()
    if not model or len(model) > 80:
        raise ValueError("预设 modelNumber 不能为空或超过 80 字符")
    params = preset.get("params")
    if not isinstance(params, dict):
        raise ValueError(f"预设 {model} 缺少 params")
    unknown = set(params) - schema_names
    if unknown:
        raise ValueError(f"预设 {model} 含未声明参数: {', '.join(sorted(unknown)[:5])}")
    return {**preset, "modelNumber": model, "params": params}


def _fill_preset_defaults(component: dict, preset: dict) -> dict:
    params = dict(preset.get("params") or {})
    for item in component.get("parameters", {}).get("schema", []):
        if item.get("access") != "out" and item.get("name") not in params and "default" in item:
            params[item["name"]] = item["default"]
    return {**preset, "params": params}


def _apply_operations(component: dict, operations: list) -> tuple[bool, str | None, list[str]]:
    parameters = component.setdefault("parameters", {})
    schema = list(parameters.get("schema") or [])
    presets = list(parameters.get("presets") or [])
    identity = component.setdefault("identity", {})
    changed = []
    rebuild = False
    selected_model = None

    for operation in operations:
        if not isinstance(operation, dict):
            raise ValueError("operation 必须是对象")
        op = str(operation.get("op") or "")
        if op == "identity.update":
            updates = operation.get("value") or {}
            if not isinstance(updates, dict):
                raise ValueError("identity.update.value 必须是对象")
            _clean_identity(identity, updates)
            changed.append("identity")
        elif op == "description.update":
            text = str(operation.get("value") or "").strip()
            if len(text) > 4000:
                raise ValueError("description 过长")
            component["description"] = text
            changed.append("description")
        elif op == "parameters.schema.update":
            schema = _validate_schema(operation.get("value") or [])
            parameters["schema"] = schema
            changed.append("parameters.schema")
            rebuild = True
        elif op == "parameters.replace":
            value = operation.get("value") or {}
            if not isinstance(value, dict):
                raise ValueError("parameters.replace.value 必须是对象")
            schema = _validate_schema(value.get("schema") or [])
            names = {item["name"] for item in schema}
            incoming = value.get("presets") or []
            if not isinstance(incoming, list) or not incoming:
                raise ValueError("parameters.replace 至少需要一个预设")
            seen = set()
            presets = []
            for item in incoming:
                preset = _validate_preset(item, names)
                if preset["modelNumber"] in seen:
                    raise ValueError(f"预设 modelNumber 重复: {preset['modelNumber']}")
                seen.add(preset["modelNumber"])
                presets.append(_fill_preset_defaults({**component, "parameters": {"schema": schema}}, preset))
            selected_model = presets[0]["modelNumber"]
            changed.append("parameters.replace")
            rebuild = True
        elif op == "parameters.presets.upsert":
            preset = _validate_preset(operation.get("value") or {}, {item["name"] for item in schema})
            preset = _fill_preset_defaults(component, preset)
            model = preset["modelNumber"]
            index = next((i for i, item in enumerate(presets) if item.get("modelNumber") == model), -1)
            if index >= 0:
                presets[index] = {**presets[index], **preset}
            else:
                presets.append(preset)
            selected_model = model
            changed.append(f"parameters.presets.upsert:{model}")
            rebuild = True
        elif op == "parameters.presets.delete":
            model = str(operation.get("value") or operation.get("modelNumber") or "").strip()
            if not model:
                raise ValueError("presets.delete 缺少 modelNumber")
            next_presets = [item for item in presets if item.get("modelNumber") != model]
            if len(next_presets) == len(presets):
                raise ValueError(f"预设不存在: {model}")
            if not next_presets:
                raise ValueError("至少保留一个预设")
            presets = next_presets
            changed.append(f"parameters.presets.delete:{model}")
        elif op == "changelog.append":
            note = str(operation.get("value") or "").strip()
            if note:
                component.setdefault("changelog", []).append({
                    "version": str(component.get("identity", {}).get("revision") or ""),
                    "date": datetime.now(timezone.utc).date().isoformat(),
                    "author": str(operation.get("actor") or "RCIF-Studio"),
                    "type": "note",
                    "changes": [note[:1000]],
                })
                changed.append("changelog")
        else:
            raise ValueError(f"不支持的编辑操作: {op}")

    parameters["schema"] = schema
    parameters["presets"] = presets
    return rebuild, selected_model, changed


def _rebuild(component: dict, work: str, generator_path: str, preset_model: str | None) -> dict:
    presets = component.get("parameters", {}).get("presets") or []
    if not presets:
        raise ValueError("没有可用预设")
    preset = presets[0]
    if preset_model:
        preset = next((item for item in presets if item.get("modelNumber") == preset_model), preset)
    params = dict(preset.get("params") or {})
    for item in component.get("parameters", {}).get("schema", []):
        if item.get("access") != "out" and item.get("name") not in params and "default" in item:
            params[item["name"]] = item["default"]

    built = _execute_generator(generator_path, params) or {}
    if not built:
        raise RuntimeError("生成器返回空部件集合")
    parts = OrderedDict((key, _shape(shape)) for key, shape in built.items())
    for key, shape in parts.items():
        if not hasattr(shape, "Volume"):
            raise TypeError(f"部件 {key} 不是 CadQuery Shape")

    for name in ("geometry", "display"):
        os.makedirs(os.path.join(work, name), exist_ok=True)
    assembly = cq.Assembly()
    for key, shape in parts.items():
        assembly.add(shape, name=key)
    assembly.save(os.path.join(work, "geometry", "default.step"), exportType="STEP")

    old_shapes = component.get("shapes") or {}
    colors = [(0.72, 0.71, 0.67), (0.58, 0.67, 0.80), (0.62, 0.72, 0.62)]

    def normalize(value: str) -> str:
        return re.sub(r"[^a-z0-9]", "", str(value).lower())

    instance_parents = {}
    for parent_key, previous in old_shapes.items():
        for instance in previous.get("instances") or []:
            instance_parents[normalize(instance)] = (parent_key, instance)

    groups: "OrderedDict[str, dict]" = OrderedDict()
    for part_key, shape in parts.items():
        hit = instance_parents.get(normalize(part_key))
        if part_key in old_shapes:
            target, node = part_key, old_shapes[part_key].get("node") or part_key
        elif hit:
            target, node = hit
        else:
            target, node = part_key, old_shapes.get(part_key, {}).get("node") or part_key
        group = groups.setdefault(target, {
            "previous": old_shapes.get(target) or {},
            "parts": [],
            "volume": 0.0,
            "nodes": [],
        })
        volume = round(shape.Volume() / 1e9, 3)
        group["parts"].append((part_key, shape, node))
        group["nodes"].append(node)
        group["volume"] += volume

    bounds = {"x": [float("inf"), float("-inf")], "y": [float("inf"), float("-inf")], "z": [float("inf"), float("-inf")]}
    shape_meta = OrderedDict()
    glb_items = []
    total_volume = 0.0
    item_index = 0
    for target, group in groups.items():
        previous = group["previous"]
        volume = round(group["volume"], 3)
        total_volume += volume
        node = previous.get("node") or group["nodes"][0] or target
        shape_meta[target] = {
            **previous,
            "label": previous.get("label") or target,
            "code": previous.get("code") or f"Generic.{target}",
            "geomType": "solid",
            "material": previous.get("material") or "C35",
            "node": node,
            "volumeM3": volume,
        }
        if len(group["parts"]) > 1:
            shape_meta[target]["instances"] = previous.get("instances") or group["nodes"]
        for part_key, shape, part_node in group["parts"]:
            box = shape.BoundingBox()
            bounds["x"] = [min(bounds["x"][0], box.xmin), max(bounds["x"][1], box.xmax)]
            bounds["y"] = [min(bounds["y"][0], box.ymin), max(bounds["y"][1], box.ymax)]
            bounds["z"] = [min(bounds["z"][0], box.zmin), max(bounds["z"][1], box.zmax)]
            vertices, triangles = shape.tessellate(1.0, 0.08)
            instance_tag = part_node.split("/", 1)[1] if "/" in part_node else part_key
            glb_items.append({
                "name": part_node,
                "verts": [(v.x, v.y, v.z) for v in vertices],
                "tris": [tuple(t) for t in triangles],
                "color": colors[item_index % len(colors)],
                "material": shape_meta[target]["material"],
                "extras": {
                    "shapeKey": target,
                    "instanceTag": instance_tag,
                    "material": shape_meta[target]["material"],
                    "label": shape_meta[target]["label"],
                    "code": shape_meta[target]["code"],
                    "volumeM3": round(shape.Volume() / 1e9, 3),
                },
            })
            item_index += 1
    # Semantic faces/selectors are not generator parts; preserve them.
    for key, previous in old_shapes.items():
        if key not in shape_meta and previous.get("geomType") != "solid":
            shape_meta[key] = previous
    write_glb_parts(glb_items, os.path.join(work, "display", "preview.glb"))

    for axis in ("x", "y", "z"):
        bounds[axis] = [round(bounds[axis][0], 3), round(bounds[axis][1], 3)]
    params["NetVolume"] = round(total_volume, 3)
    with open(generator_path, "rb") as handle:
        digest = hashlib.sha256(handle.read()).hexdigest()
    cache_key = rcifc.compute_cache_key(digest, params)
    component["shapes"] = shape_meta
    component.setdefault("geometry", {}).update({
        "exactBrep": True,
        "defaultFormat": "step",
        "file": "geometry/default.step",
        "defaultFile": "geometry/default.step",
        "display": "display/preview.glb",
        "bounds": bounds,
        "volumeM3": round(total_volume, 3),
        "defaultCacheKey": cache_key,
        "naming": {
            **(component.get("geometry", {}).get("naming") or {}),
            "nodeNames": [item["name"] for item in glb_items],
        },
    })
    component.setdefault("recipe", {}).update({
        "engine": "cadquery",
        "source": "generators/generator.py",
        "entry": "build_parts",
        "version": "1.4.2",
        "digest": digest,
        "inputs": [item.get("name") for item in component.get("parameters", {}).get("schema", []) if item.get("access") != "out"],
    })
    preset = {
        **preset,
        "params": params,
        "isPrebaked": True,
        "cacheKey": cache_key,
    }
    parameter_presets = component.get("parameters", {}).get("presets") or []
    index = next((i for i, item in enumerate(parameter_presets) if item.get("modelNumber") == preset.get("modelNumber")), 0)
    parameter_presets[index] = preset
    component["parameters"]["presets"] = parameter_presets
    qa = component.setdefault("qa", {})
    qa["geometryValid"] = True
    qa["presetCount"] = len(parameter_presets)
    qa["partVolumes"] = {key: value["volumeM3"] for key, value in shape_meta.items() if "volumeM3" in value}
    return {
        "revision": None,
        "volumeM3": round(total_volume, 3),
        "bounds": bounds,
        "shapeCount": len(groups),
        "params": params,
        "preset": preset.get("modelNumber"),
    }


def edit(package_path: str, operations: list, output: str | None = None,
         revision: str | None = None, note: str = "", actor: str = "RCIF-Studio",
         base_sha256: str | None = None) -> tuple[str, dict]:
    package_path = os.path.abspath(package_path)
    if not os.path.isfile(package_path):
        raise FileNotFoundError(f"构件包不存在: {package_path}")
    if not isinstance(operations, list) or not operations:
        raise ValueError("operations 不能为空")
    if base_sha256:
        actual = hashlib.sha256(open(package_path, "rb").read()).hexdigest()
        if actual.lower() != base_sha256.lower():
            raise RuntimeError("PACKAGE_CHANGED: 构件包已被其他操作修改，请重新加载")

    work = tempfile.mkdtemp(prefix="rcif_package_edit_")
    try:
        _safe_extract(package_path, work)
        component_path = os.path.join(work, "component.json")
        with open(component_path, encoding="utf-8") as handle:
            component = json.load(handle)
        if component.get("format") != "cbf-component":
            raise ValueError("不是 RCIF component 包")
        rebuild, selected_model, changed = _apply_operations(component, operations)
        generator_path = os.path.join(work, "generators", "generator.py")
        info = {}
        if rebuild:
            if not os.path.isfile(generator_path):
                raise FileNotFoundError("该包没有 generators/generator.py，无法重建几何")
            info = _rebuild(component, work, generator_path, selected_model)

        current_revision = str(component.get("identity", {}).get("revision") or "0.0.0")
        next_revision = revision or _bump_revision(current_revision)
        if not re.match(r"^\d+\.\d+\.\d+$", next_revision):
            raise ValueError("revision 必须是 x.y.z")
        if next_revision == current_revision:
            raise ValueError("修改必须生成新版本，revision 不能与原版本相同")
        identity = component.setdefault("identity", {})
        identity["revision"] = next_revision
        component.setdefault("changelog", []).append({
            "version": next_revision,
            "date": datetime.now(timezone.utc).date().isoformat(),
            "author": actor,
            "type": "edit",
            "changes": [note or "通过工作台编辑", *changed],
        })
        component.setdefault("qa", {}).setdefault("edits", []).append({
            "at": _now(),
            "actor": actor,
            "note": note,
            "operations": changed,
            "baseRevision": current_revision,
        })
        component["qa"]["edits"] = component["qa"]["edits"][-30:]
        component.get("qa", {}).pop("packageSha256", None)

        if not output:
            stem = os.path.splitext(os.path.basename(package_path))[0]
            output = os.path.join(os.path.dirname(package_path), f"{stem}_{next_revision}.rcif")
        output = os.path.abspath(output)
        if output == package_path:
            raise ValueError("不允许覆盖原构件包，必须输出新版本")
        os.makedirs(os.path.dirname(output), exist_ok=True)
        pkg, pkg_sha = rcifc.build_rcif_package(work, output, component)
        return pkg, {
            "packagePath": pkg,
            "packageSha256": pkg_sha,
            "revision": next_revision,
            "name": component.get("identity", {}).get("name"),
            "changed": changed,
            "rebuild": rebuild,
            "volumeM3": info.get("volumeM3"),
            "bounds": info.get("bounds"),
            "shapeCount": info.get("shapeCount"),
        }
    finally:
        shutil.rmtree(work, ignore_errors=True)


def main() -> int:
    parser = argparse.ArgumentParser(description="按白名单编辑 RCIF 构件包并生成新版本")
    parser.add_argument("package")
    parser.add_argument("--ops-json", default=None)
    parser.add_argument("--ops-file", default=None)
    parser.add_argument("--output", default=None)
    parser.add_argument("--revision", default=None)
    parser.add_argument("--note", default="")
    parser.add_argument("--actor", default="RCIF-Studio")
    parser.add_argument("--base-sha256", default=None)
    args = parser.parse_args()
    if args.ops_file:
        with open(args.ops_file, encoding="utf-8-sig") as handle:
            operations = json.load(handle)
    else:
        operations = json.loads(args.ops_json or "[]")
    if not isinstance(operations, list):
        raise SystemExit("ops-json 必须是数组")
    pkg, info = edit(
        args.package, operations, args.output, args.revision,
        args.note, args.actor, args.base_sha256,
    )
    print(json.dumps({"ok": True, "packagePath": pkg, **info}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
